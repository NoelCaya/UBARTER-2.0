  {{-- 1. Overview --}}
  <div class="card">
    <h2 class="section-title"><i class="fas fa-info-circle"></i> 1. Overview</h2>
    <p>UBARTER is a peer-to-peer barter and donation platform developed exclusively for the University of Batangas (UB) community. This Data Privacy Policy explains how we collect, use, store, and protect your personal information when you use the UBARTER platform.</p>
    <p>By accessing or using UBARTER, you agree to the terms described in this policy. If you do not agree, please do not use the platform.</p>
  </div>

  {{-- 2. Information We Collect --}}
  <div class="card">
    <h2 class="section-title"><i class="fas fa-database"></i> 2. Information We Collect</h2>
    <p>We collect the following types of information when you use UBARTER:</p>
    <ul>
      <li><strong>Account Information:</strong> Your UB email address (UBmail), name, and profile picture when you sign in through Google/UBmail SSO.</li>
      <li><strong>Item Listings:</strong> Photos, titles, descriptions, and category information of items you post for barter or donation.</li>
      <li><strong>Trade & Transaction Data:</strong> Records of barter proposals, accepted trades, completed exchanges, and donation claims.</li>
      <li><strong>Messages:</strong> Conversations you have with other users through the UBARTER messaging system.</li>
      <li><strong>Activity Data:</strong> Pages viewed, items browsed, wishlist activity, and reviews submitted.</li>
      <li><strong>Reports:</strong> Reports you submit about other users and responses related to those reports.</li>
    </ul>
  </div>

  {{-- 3. How We Use Your Information --}}
  <div class="card">
    <h2 class="section-title"><i class="fas fa-cogs"></i> 3. How We Use Your Information</h2>
    <p>Your information is used solely for the operation and improvement of the UBARTER platform. Specifically, we use it to:</p>
    <ul>
      <li>Authenticate your identity and verify your UB community membership.</li>
      <li>Facilitate barter trades, donation listings, and claim requests between users.</li>
      <li>Enable communication between users through the in-platform messaging system.</li>
      <li>Maintain platform safety through user reports and admin moderation.</li>
      <li>Display your name and profile on listings, trade history, and the reputation wall.</li>
      <li>Send in-platform notifications about trades, messages, and account activity.</li>
    </ul>
    <div class="highlight">
      <i class="fas fa-exclamation-triangle"></i>
      <span>We do <strong>not</strong> sell, rent, or share your personal information with third parties for marketing or commercial purposes.</span>
    </div>
  </div>

  {{-- 4. Data Sharing --}}
  <div class="card">
    <h2 class="section-title"><i class="fas fa-share-alt"></i> 4. Data Sharing</h2>
    <p>Your information may be visible to other UBARTER users in the following limited ways:</p>
    <ul>
      <li>Your <strong>name</strong> and <strong>profile picture</strong> are visible on your item listings, trade proposals, and the reputation wall.</li>
      <li>Your <strong>UBmail address</strong> is visible only to UBARTER administrators for moderation purposes.</li>
      <li>Messages you send are visible only to the recipient and UBARTER administrators in cases of reported violations.</li>
    </ul>
    <p>UBARTER is integrated with <strong>Google OAuth</strong> for authentication. Your sign-in is processed by Google under their own privacy terms. UBARTER only receives your name and email address from Google.</p>
  </div>

  {{-- 5. Data Retention --}}
  <div class="card">
    <h2 class="section-title"><i class="fas fa-clock"></i> 5. Data Retention</h2>
    <p>We retain your data for as long as your account is active on the UBARTER platform. If you delete your account, your personal information, item listings, and messages will be permanently removed from the platform.</p>
    <p>Some aggregated, non-identifiable data may be retained for academic and administrative reporting purposes.</p>
  </div>

  {{-- 6. Data Security --}}
  <div class="card">
    <h2 class="section-title"><i class="fas fa-lock"></i> 6. Data Security</h2>
    <p>We take reasonable technical and administrative measures to protect your personal information from unauthorized access, disclosure, or misuse. These include:</p>
    <ul>
      <li>HTTPS encryption for all data transmitted between your device and the platform.</li>
      <li>Secure authentication through Google/UBmail OAuth — no passwords are stored by UBARTER.</li>
      <li>Role-based access control ensuring only authorized administrators can access sensitive data.</li>
      <li>Regular monitoring of platform activity for suspicious behavior.</li>
    </ul>
  </div>

  {{-- 7. Your Rights --}}
  <div class="card">
    <h2 class="section-title"><i class="fas fa-user-shield"></i> 7. Your Rights</h2>
    <p>As a UBARTER user, you have the right to:</p>
    <ul>
      <li><strong>Access</strong> the personal information we hold about you by visiting your profile page.</li>
      <li><strong>Update</strong> your profile picture and display name through your profile settings.</li>
      <li><strong>Delete</strong> your account and all associated data at any time through the Danger Zone section of your profile.</li>
      <li><strong>Report</strong> concerns about how your data is being handled by contacting a UBARTER administrator through the platform.</li>
    </ul>
  </div>

  {{-- 8. Platform-Specific Rules --}}
  <div class="card">
    <h2 class="section-title"><i class="fas fa-gavel"></i> 8. Platform Rules & Acceptable Use</h2>
    <p>To protect all users, the following rules apply on UBARTER:</p>
    <ul>
      <li>You may only register using a valid, active <strong>UBmail address</strong> (@ub.edu.ph).</li>
      <li>You must not post items you do not personally own or have the right to trade.</li>
      <li>Submitting false or malicious reports against other users is strictly prohibited and may result in account suspension.</li>
      <li>All barter trades and donation claims are conducted between users. UBARTER is not responsible for the outcome of physical exchanges.</li>
      <li>Always meet in well-lit, public campus areas when exchanging items.</li>
    </ul>
  </div>

  {{-- 9. Contact --}}
  <div class="card">
    <h2 class="section-title"><i class="fas fa-envelope"></i> 9. Contact & Concerns</h2>
    <p>If you have questions, concerns, or requests regarding this Data Privacy Policy or how your information is handled, please contact a UBARTER administrator through the platform's messaging system or report feature.</p>
    <p>This policy is subject to change. Continued use of UBARTER after any changes constitutes acceptance of the updated policy.</p>
